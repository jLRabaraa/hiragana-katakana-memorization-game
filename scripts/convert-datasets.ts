/**
 * Curriculum enrichment pipeline.
 *
 * Source of truth: src/data/curated/*.ts (hand-authored).
 * Raw inputs:      data/raw/ (git-ignored; see docs/DATA-PIPELINE.md)
 * Output:          src/data/generated/*.generated.ts (committed)
 *
 * Run with Node's native TypeScript support (Node 22.18+):
 *   node scripts/convert-datasets.ts
 *
 * The script is deterministic, never edits curated files, and falls back to the
 * curated fields (with a warning) when the raw datasets are absent.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { gunzipSync } from 'node:zlib'
import { CURATED_VOCAB } from '../src/data/curated/vocab.ts'
import type { KanjiInfo, VocabItem } from '../src/types/domain.ts'

const ROOT = process.cwd()
const RAW = path.join(ROOT, 'data', 'raw')
const OUT = path.join(ROOT, 'src', 'data', 'generated')

const HEADER = `/**
 * AUTO-GENERATED by scripts/convert-datasets.ts — do not edit by hand.
 *
 * Dictionary data derived from JMdict and KANJIDIC2, © Electronic Dictionary
 * Research and Development Group, licensed CC BY-SA 3.0.
 * Example sentences derived from Tatoeba, licensed CC BY 2.0 FR.
 * See THIRD_PARTY_LICENSES.md.
 */`

function warn(message: string): void {
  console.warn(`  ! ${message}`)
}

function ok(message: string): void {
  console.log(`  ✓ ${message}`)
}

function firstExisting(candidates: string[]): string | null {
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate
  }
  return null
}

function readText(file: string): string {
  const buffer = readFileSync(file)
  const data = file.endsWith('.gz') ? gunzipSync(buffer) : buffer
  return data.toString('utf8')
}

/* ------------------------------------------------------------------ JMdict */

function parseJmdict(xml: string): Map<string, string[]> {
  const map = new Map<string, string[]>()
  for (const entry of xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)) {
    const body = entry[1]
    const keys = [
      ...body.matchAll(/<keb>([^<]+)<\/keb>/g),
      ...body.matchAll(/<reb>([^<]+)<\/reb>/g),
    ].map((match) => match[1])
    const glosses = [...body.matchAll(/<gloss[^>]*>([^<]*)<\/gloss>/g)]
      .slice(0, 4)
      .map((match) => match[1].trim())
      .filter(Boolean)

    for (const key of keys) {
      if (!map.has(key)) map.set(key, glosses)
    }
  }
  return map
}

/* --------------------------------------------------------------- KANJIDIC2 */

function parseKanjidic(xml: string): Map<string, KanjiInfo> {
  const map = new Map<string, KanjiInfo>()
  for (const character of xml.matchAll(/<character>([\s\S]*?)<\/character>/g)) {
    const body = character[1]
    const literal = body.match(/<literal>([^<]+)<\/literal>/)?.[1]
    if (!literal) continue

    const meanings = [...body.matchAll(/<meaning(?:\s+m_lang="en")?>([^<]+)<\/meaning>/g)].map(
      (match) => match[1],
    )
    const on = [...body.matchAll(/<reading r_type="ja_on">([^<]+)<\/reading>/g)].map(
      (match) => match[1],
    )
    const kun = [...body.matchAll(/<reading r_type="ja_kun">([^<]+)<\/reading>/g)].map(
      (match) => match[1],
    )
    const gradeText = body.match(/<grade>(\d+)<\/grade>/)?.[1]
    const grade = gradeText ? Number(gradeText) : undefined

    map.set(literal, {
      literal,
      meanings,
      on,
      kun,
      ...(grade ? { grade } : {}),
    })
  }
  return map
}

/* ----------------------------------------------------------------- Tatoeba */

interface TatoebaIndex {
  japanese: Map<string, string>
  english: Map<string, string>
  links: Map<string, string[]>
}

function readTsv(file: string): string[][] {
  return readText(file)
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => line.split('\t'))
}

function loadTatoeba(): TatoebaIndex | null {
  const japaneseFile = firstExisting([
    path.join(RAW, 'tatoeba', 'jpn.tsv'),
    path.join(RAW, 'tatoeba', 'sentences_jpn.tsv'),
  ])
  const englishFile = firstExisting([
    path.join(RAW, 'tatoeba', 'eng.tsv'),
    path.join(RAW, 'tatoeba', 'sentences_eng.tsv'),
  ])
  const linksFile = firstExisting([path.join(RAW, 'tatoeba', 'links.tsv')])

  if (!japaneseFile || !englishFile || !linksFile) return null

  const japanese = new Map<string, string>()
  for (const row of readTsv(japaneseFile)) {
    if (row.length >= 2) japanese.set(row[0], row[1])
  }

  const english = new Map<string, string>()
  for (const row of readTsv(englishFile)) {
    if (row.length >= 2) english.set(row[0], row[1])
  }

  const links = new Map<string, string[]>()
  for (const row of readTsv(linksFile)) {
    if (row.length < 2) continue
    const current = links.get(row[0]) ?? []
    current.push(row[1])
    links.set(row[0], current)
  }

  return { japanese, english, links }
}

function findExample(index: TatoebaIndex, word: VocabItem): { ja: string; en: string } | null {
  const needle = word.kanji ?? word.kana
  const candidates: { id: string; text: string }[] = []

  for (const [id, text] of index.japanese) {
    if (!text.includes(needle)) continue
    // Keep sentences short enough to fit a lesson card.
    if (text.length > 24) continue
    candidates.push({ id, text })
  }

  candidates.sort((a, b) => a.text.length - b.text.length)

  for (const candidate of candidates.slice(0, 20)) {
    for (const linkedId of index.links.get(candidate.id) ?? []) {
      const translation = index.english.get(linkedId)
      if (translation) return { ja: candidate.text, en: translation }
    }
  }
  return null
}

/* -------------------------------------------------------------------- main */

function validateCurated(): string[] {
  const problems: string[] = []
  const seen = new Set<string>()

  for (const item of CURATED_VOCAB) {
    if (seen.has(item.id)) problems.push(`duplicate vocabulary id: ${item.id}`)
    seen.add(item.id)
    if (!item.kana || !item.gloss) problems.push(`incomplete vocabulary item: ${item.id}`)
    if (!/^[\p{Script=Hiragana}\p{Script=Katakana}\u30FC]+$/u.test(item.kana)) {
      problems.push(`reading is not kana: ${item.id} (${item.kana})`)
    }
    if (
      item.kanji &&
      !(
        /\p{Script=Han}/u.test(item.kanji) &&
        /^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\u30FC]+$/u.test(item.kanji)
      )
    ) {
      problems.push(`written form must contain kanji and only Japanese script: ${item.id}`)
    }
  }
  return problems
}

function main(): void {
  console.log('Kana Dōjō · curriculum enrichment')
  console.log('----------------------------------')

  const problems = validateCurated()
  if (problems.length) {
    for (const problem of problems) warn(problem)
    process.exitCode = 1
    return
  }
  ok(`${CURATED_VOCAB.length} curated words validated`)

  const jmdictFile = firstExisting([
    path.join(RAW, 'JMdict_e.gz'),
    path.join(RAW, 'JMdict_e.xml'),
    path.join(RAW, 'JMdict_e'),
  ])
  const kanjidicFile = firstExisting([
    path.join(RAW, 'kanjidic2.xml.gz'),
    path.join(RAW, 'kanjidic2.xml'),
  ])

  let jmdict: Map<string, string[]> | null = null
  if (jmdictFile) {
    jmdict = parseJmdict(readText(jmdictFile))
    ok(`JMdict loaded: ${jmdict.size.toLocaleString()} keys`)
  } else {
    warn('JMdict not found in data/raw/ — glosses stay curated')
  }

  let kanjidic: Map<string, KanjiInfo> | null = null
  if (kanjidicFile) {
    kanjidic = parseKanjidic(readText(kanjidicFile))
    ok(`KANJIDIC2 loaded: ${kanjidic.size.toLocaleString()} characters`)
  } else {
    warn('KANJIDIC2 not found in data/raw/ — kanji readings stay empty')
  }

  const tatoeba = loadTatoeba()
  if (tatoeba) {
    ok(`Tatoeba loaded: ${tatoeba.japanese.size.toLocaleString()} Japanese sentences`)
  } else {
    warn('Tatoeba not found in data/raw/tatoeba/ — curated examples are kept')
  }

  let examplesAttached = 0
  const enriched: VocabItem[] = CURATED_VOCAB.map((item) => {
    const dictGlosses = jmdict?.get(item.kanji ?? item.kana) ?? jmdict?.get(item.kana)
    const example = tatoeba ? findExample(tatoeba, item) : null
    if (example) examplesAttached += 1

    return {
      ...item,
      // Manual gloss always wins; dictionary glosses are only a fallback.
      gloss: item.gloss || dictGlosses?.[0] || item.gloss,
      ...(example ? { example } : {}),
    }
  })

  const kanjiLiterals = [
    ...new Set(
      CURATED_VOCAB.flatMap((item) =>
        item.kanji ? Array.from(item.kanji).filter((char) => /\p{Script=Han}/u.test(char)) : [],
      ),
    ),
  ]
  const kanji: KanjiInfo[] = kanjiLiterals.map((literal) => {
    const fromDataset = kanjidic?.get(literal)
    return (
      fromDataset ?? {
        literal,
        meanings: [],
        on: [],
        kun: [],
      }
    )
  })

  mkdirSync(OUT, { recursive: true })

  writeFileSync(
    path.join(OUT, 'vocab.generated.ts'),
    `${HEADER}\n\nimport type { VocabItem } from '../../types/domain'\n\nexport const GENERATED_VOCAB: VocabItem[] = ${JSON.stringify(enriched, null, 2)}\n`,
  )

  writeFileSync(
    path.join(OUT, 'kanji.generated.ts'),
    `${HEADER}\n\nimport type { KanjiInfo } from '../../types/domain'\n\nexport const GENERATED_KANJI: KanjiInfo[] = ${JSON.stringify(kanji, null, 2)}\n`,
  )

  ok(`${enriched.length} vocabulary entries written`)
  ok(`${kanji.length} kanji entries written`)
  ok(`${examplesAttached} Tatoeba examples attached`)

  if (!jmdict && !kanjidic && !tatoeba) {
    console.log('\nNo raw datasets found. Generated files mirror the curated content.')
    console.log('See docs/DATA-PIPELINE.md for download and export instructions.')
  }
}

main()
